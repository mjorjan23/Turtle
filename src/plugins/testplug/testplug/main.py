import turtle
t = turtle.Turtle()
def function1():
    t.penup()
    t.goto(-150, 50)
    t.pendown()
    t.right(90)
    t.forward(100)
    t.left(90)
    t.forward(50)
def function2():
    t.penup()
    t.goto(-30, -50)
    t.pendown()
    t.left(75)
    t.forward(105)
    t.right(150)
    t.forward(105)
    t.penup()
    t.left(75)
    t.forward(-40)
    t.goto(-10, 0)
    t.pendown()
    t.forward(25)
function1()
function2()
turtle.done()